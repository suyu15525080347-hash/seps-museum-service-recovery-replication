#!/usr/bin/env python3
"""Leave-one-mission-out stress test for five-mission recovery masking benchmark."""
from pathlib import Path
import csv,json,statistics,collections
import numpy as np
root=next(q for p in Path('G:/').iterdir() if p.is_dir() for q in p.iterdir() if q.is_dir() and 'Cities+SEPS' in q.name)
out=next(root.glob('05_*'))/'33_UK_DCMS_robust_early_warning_benchmark_vs_equal_weight_v1'
with (out/'UK_DCMS_museum_year_robust_warning_vs_equalweight_VISITOR_benchmark_v1.csv').open(encoding='utf-8-sig') as f:rows=[r for r in csv.DictReader(f) if r['dimension_set']=='core5']
dims=['total_visits','under16','formal_education','onsite_U18','UK_loan_venues']
def parse(r):
 return np.array([float(x) for x in r['capped_attainment_pipe'].split('|')],float)
sets=[('all5',dims,list(range(5)))]
for j,d in enumerate(dims):sets.append(('drop_'+d,[x for x in dims if x!=d],[i for i in range(5) if i!=j]))
summary=[];detail=[]
for label,names,inds in sets:
 spans=[];states=collections.Counter();mask90=0;eq90=0;all90=0;mask80=0
 for r in rows:
  a=parse(r)[inds];eq=float(a.mean());mn=float(a.min());mx=float(a.max())
  span=eq-mn;spans.append(span)
  state90='GREEN' if mn>=.9-1e-12 else ('RED' if mx<.9-1e-12 else 'AMBER')
  states[state90]+=1
  mask90+=int(eq>=.9-1e-12 and mn<.9-1e-12);eq90+=int(eq>=.9-1e-12);all90+=int(mn>=.9-1e-12)
  mask80+=int(eq>=.8-1e-12 and mn<.8-1e-12)
  detail.append({'variant':label,'museum_group':r['museum_group'],'financial_year':r['financial_year'],
   'missions_pipe':'|'.join(names),'equalweight':round(eq,8),'min_mission':round(mn,8),'max_mission':round(mx,8),
   'masking_span':round(span,8),'state90':state90,'equal_pass90_but_not_all':int(eq>=.9-1e-12 and mn<.9-1e-12)})
 summary.append({'variant':label,'n_missions':len(inds),'museum_years':len(rows),
   'mean_masking_span':round(statistics.mean(spans),4),'median_masking_span':round(statistics.median(spans),4),
   'masking_cases_t090':mask90,'equalweight_pass_t090':eq90,'allmissions_pass_t090':all90,
   'masking_cases_t080':mask80,'state90_RED':states['RED'],'state90_AMBER':states['AMBER'],'state90_GREEN':states['GREEN']})
with (out/'UK_DCMS_leave_one_mission_out_warning_robustness_summary_v1.csv').open('w',encoding='utf-8-sig',newline='') as f:
 w=csv.DictWriter(f,fieldnames=list(summary[0]));w.writeheader();w.writerows(summary)
with (out/'UK_DCMS_leave_one_mission_out_warning_robustness_detail_v1.csv').open('w',encoding='utf-8-sig',newline='') as f:
 w=csv.DictWriter(f,fieldnames=list(detail[0]));w.writeheader();w.writerows(detail)
qa={'variants':summary,
 'pre_specified_reason':'Reviewer stress test: assess whether the masking result is generated by a single mission indicator.',
 'pass_rule':'Qualitative robustness if every leave-one-out variant retains positive mean masking span and nonzero equal-weight pass-but-not-all-mission cases at at least one transparent threshold, without selecting which mission to omit after seeing results.',
 'not_model_selection':'No leave-one-out variant replaces the main five-mission specification; all variants are reported.'}
(out/'UK_DCMS_leave_one_mission_out_warning_QA_v1.json').write_text(json.dumps(qa,ensure_ascii=False,indent=2),encoding='utf-8')
print('LEAVE_ONE_MISSION_OUT',json.dumps(summary,ensure_ascii=False),flush=True)
